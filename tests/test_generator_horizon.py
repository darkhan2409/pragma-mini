def test_repeat_gives_the_same_manifest(runs):

    def card(directory) -> dict:
        record = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
        record.pop("created_at", None)
        return record

    assert card(runs["short"]) == card(runs["again"])


