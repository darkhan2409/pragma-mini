# ------------------------------------------------------------
# ЧТО ВИДИТ МОДЕЛЬ СВЕРХ PAYLOAD
# ------------------------------------------------------------
#
# Проекция пропускает только то, что лежит в самой строке,
# и сверх этого добавляется ровно два вида значений:
# локальные ссылки вместо сырых идентификаторов и прежнее
# с новым значением изменившегося поля анкеты в его
# собственном смысле.
#
# Расчётных и временных признаков больше нет ни одного:
# отдельного смыслового этапа, который их считал, в конвейере
# нет, и обещать их модели было бы неправдой.
# ------------------------------------------------------------


# ============================================================
# МОДЕЛЬНОЕ СОБЫТИЕ
# ============================================================


@dataclass(frozen=True)
class ModelEvent:
    client_id: str
    event_time: datetime
    source: str
    fields: dict

    def as_dict(self) -> dict:
        return {
            "client_id": self.client_id,
            "event_time": self.event_time,
            "source": self.source,
            "fields": dict(self.fields),
        }


def model_event(row: dict) -> ModelEvent:
    """
    Строит модельное событие из строки очищенной истории.

    Проходит только то, что названо разрешённым: смысловые поля
    payload и тип события.
    """

    fields: dict = {EVENT_TYPE_FIELD: row[EVENT_TYPE_FIELD]}

    for name in SEMANTIC_PAYLOAD_FIELDS:
        value = row.get(name)
        if value is not None:
            fields[name] = value

    return ModelEvent(
        client_id=row["client_id"],
        event_time=row["event_time"],
        source=row["source"],
        fields=fields,
    )


# ============================================================
# РЕЕСТР И ПРОВЕРКА
# ============================================================


def model_role(name: str) -> str:
    """
    Судьба поля: смысловое значение или внутреннее поле
    слоя. Третьего исхода нет: локальных ссылок больше нет.
    """

    if name in SEMANTIC_PAYLOAD_FIELDS:
        return "semantic_field"

    return "internal"


def validate_projection(payload_names: Iterable[str]) -> None:
    """
    Каждое имя payload выгрузки названо ровно один раз: либо
    разрешено, либо объявлено внутренним. Незнакомое имя
    останавливает работу.
    """

    unknown: list[str] = []
    twice: list[str] = []

    for name in sorted(set(payload_names)):

        places = sum(
            1 for table in (SEMANTIC_PAYLOAD_FIELDS, INTERNAL_FIELDS) if name in table
        )

        if places == 0:
            unknown.append(name)
        elif places > 1:
            twice.append(name)

    if unknown:
        raise ProjectionError(
            "поля выгрузки не классифицированы модельной проекцией: "
            + ", ".join(unknown)
            + ". Назовите каждое либо смысловым, либо внутренним"
        )

    if twice:
        raise ProjectionError("поля названы дважды: " + ", ".join(twice))


