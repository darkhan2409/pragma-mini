# ============================================================
# ИДЕЯ
# ============================================================
#
# Контракт транзакции не раскрывает торговую точку:
#
#     ts, amount, direction, mcc, merchant_city,
#     merchant_country, is_online, is_subscription
#
# Поэтому каталога мерчантов нет. Есть категории расходов,
# у каждой свой набор MCC, типичная сумма, доля онлайна,
# доля подписок, доля зарубежных операций и часы активности.
#
# MCC намеренно неравномерны: у категории один-два частых кода
# и редкий хвост, как в реальной выгрузке.
# ============================================================


