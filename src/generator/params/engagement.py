from __future__ import annotations

from dataclasses import dataclass, field


# ============================================================
# ОТНОШЕНИЯ КЛИЕНТА С БАНКОМ
# ============================================================
#
# Параметры скрытого состояния, из которого рождается
# неактивность (behaviour/engagement.py). Все значения ниже —
# СИНТЕТИЧЕСКИЕ ДОПУЩЕНИЯ: агрегатов банка, по которым их можно
# откалибровать, пока нет (audit/2026-10-06-generator-v1/
# calibration_contract.md). Ставки опасностей подобраны так, чтобы
# доля времени, когда деньги клиента молчат, по режимам
# активности была близка к прежнему плану пауз: это держит объём
# ленты у полос калибровки, а не долю оттока.
#
# Ставки — в сутки.
# ============================================================


@dataclass(frozen=True)
class EngagementParams:

    # Общий множитель режима активности: во сколько раз реже у
    # клиента этого режима начинаются уход, миграция и отлучка.
    mode_factor: dict = field(
        default_factory=lambda: {
            "silent": 1.0,
            "rare": 1.0,
            "regular": 0.6,
            "high": 0.3,
            "extreme": 0.05,
        }
    )

    # --- недовольство банком (friction) ---
    #
    # Полупериод забывания, потолок и вес каждой улики. Рутинное —
    # отказ из-за своих денег, обычные комиссии — не недовольство
    # банком, а сбой операции весит мало: недовольство — про редкие
    # заметные неприятности, а не про то, как часто клиент
    # пользуется банком. Иначе активный клиент копил бы его просто
    # от частоты операций (проверка scratch 2026-10-06: при прежних
    # весах F у extreme был в 20 раз выше, чем у silent).
    # Repricing клиент замечает не в тот же день — задержка до
    # notice_days дней разводит массовые волны.
    friction_half_life_days: float = 30.0
    friction_cap: float = 5.0
    evidence: dict = field(
        default_factory=lambda: {
            "decline_bank": 0.4,
            "failed_operation": 0.03,
            "rejected": 0.5,
            "card_block": 1.0,
            "case_declined": 0.8,
            "case_escalated": 0.3,
            "case_slow": 0.15,
            "repricing": 0.5,
            "early_closure": 0.4,
        }
    )
    case_slow_hours: int = 72
    case_relief: float = 0.5
    notice_days: int = 14

    # --- доля денежной жизни через банк ---
    #
    # x = ln(A / база): у нормы 0, во время миграции цель —
    # ln(глубины). Малый шум даёт медленный дрейф без причины.
    affinity_noise: float = 0.015
    affinity_half_life_days: float = 60.0

    # --- миграция в другой банк ---
    migration_rate: float = 4e-4
    migration_weights: dict = field(
        default_factory=lambda: {"friction": 1.0, "stress": 1.0, "ties": 0.3}
    )
    # Переезд, смена или потеря работы, развод: во сколько раз и
    # сколько дней после события миграция начинается чаще.
    life_change: tuple = (5.0, 90)
    migration_depth: tuple = (0.05, 0.4)
    migration_half_life_days: tuple = (20, 90)
    migration_rollback: tuple = (5e-3, 0.5)

    # --- уход и возвращение ---
    lapse_rate: float = 4.5e-4
    lapse_weights: dict = field(
        default_factory=lambda: {"friction": 1.5, "stress": 2.5, "deficit": 2.0, "ties": 0.3}
    )
    # Разброс склонности к уходу между клиентами (логнормальный).
    frailty_sigma: float = 0.5
    # Новый клиент уходит чаще: ×(1 + амплитуда·e^(−дни/срок)).
    onboarding: tuple = (3.0, 30)
    return_rate: float = 6e-3
    return_weights: dict = field(
        default_factory=lambda: {"friction": 0.5, "stress": 0.5, "deficit": 1.0}
    )
    # Клик по winback-предложению: во сколько раз и сколько дней
    # возвращение вероятнее.
    winback: tuple = (3.0, 30)
    # Пришёл и не начал пользоваться: через сколько дней (от, до)
    # и во сколько раз реже такой клиент возвращается.
    never_started: tuple = (1, 19, 0.15)

    # --- внешние отлучки (exogenous) ---
    #
    # От недовольства, стресса и доли банка не зависят: отпуск без
    # карты, жизнь на наличных, временная поломка телефона,
    # неизвестные причины. Летом и зимой их больше.
    away_rate: float = 1.6e-3
    away_season: float = 0.4
    away_kinds: dict = field(
        default_factory=lambda: {
            "no_app": (0.48, 30, 180),
            "no_cards": (0.26, 25, 150),
            "offline": (0.26, 30, 110),
        }
    )
    away_jitter: tuple = (0.55, 1.45)

    # --- потоки ---
    #
    # Чувствительность потока к доле банка: множитель exp(s·x),
    # s ~ LogNormal(0, sigma), обрезанный [низ, верх], свой у
    # каждого клиента; у сессий — равномерный. Недовольство
    # гасит добровольные потоки ещё и напрямую: exp(−dampening·F).
    sensitivity: tuple = (0.5, 0.3, 2.5)
    session_sensitivity: tuple = (0.0, 0.8)
    dampening: float = 0.15
    # Переводы на свой счёт в другом банке: ×(1 + outflow·(1 − e^x)).
    outflow: float = 2.0
    # Привязки — зарплата, счета и подписки — уходят из банка, когда
    # exp(s·x) ниже своего порога, и возвращаются, когда выше порога
    # + гистерезиса. Пороги низкие: уходят они при настоящем переносе
    # жизни в другой банк, а не от шума доли x.
    salary_threshold: tuple = (0.1, 0.4)
    tie_threshold: tuple = (0.1, 0.6)
    tie_hysteresis: float = 0.15
    # Ушедший клиент с долгом здесь изредка заходит в приложение по
    # делу: посмотреть график и остаток.
    servicing: float = 0.08
    # Отклик на рассылки: exp(степень·x), у ушедшего ×доля.
    response: tuple = (0.5, 0.3)
    # Обращения: ×(1 + support·F); жалоба — опасность в сутки на
    # единицу F и кулдаун в днях.
    support: float = 0.5
    complaint: tuple = (0.004, 14)

    # --- прогрев ---
    #
    # Клиент, пришедший до окна, входит в него не с нулевым
    # состоянием: оно прогоняется столько дней до начала окна, в
    # типичных условиях — недовольство, стресс и доля дней после
    # недавнего жизненного события постоянны и близки к своим
    # средним по окну (scratch 2026-10-06: средний F 0.10–0.15,
    # E[exp(2.5S)] 1.12, переезд, работа и развод — около 8% дней в
    # окне 90 дней). Жизненные события и стресс до окна не
    # разыгрываются: персона описывает клиента на начало окна.
    # Срок — дольше времени релаксации состояния: уход после
    # глубокой миграции длится год и больше.
    burn_in_days: int = 1095
    burn_in_drivers: dict = field(
        default_factory=lambda: {"friction": 0.15, "stress": 0.045, "life_change": 0.08}
    )
    # Причина перехода — член с наибольшим вкладом в log-опасность,
    # если вклад не меньше этого порога; иначе baseline.
    cause_threshold: float = 0.5
