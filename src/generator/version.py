from __future__ import annotations


# ============================================================
# ВЕРСИЯ ГЕНЕРАЦИИ
# ============================================================
#
# v1    правила первой версии: потоки согласованы через владение
#       продуктами и траекторию, но внутри потока почти всё
#       разыгрывается независимо от прошлого клиента.
#
# v2.1  те же схемы, значения и горизонт, но поведение внутри
#       потоков зависит от состояния: сценарии сессий, вход,
#       исходы операций, привычки трат, расписание счетов.
#
# v2 был промежуточным шагом и заменён на v2.1: в нём успешный
# платёж мог не иметь последствия, действия шли до завершения
# входа, а состояние применялось не в момент события. Готовый
# датасет data/raw/v2 остаётся на диске как есть, но повторно
# он не порождается: генератор исправлен, а не разветвлён.
#
# Версия по умолчанию v1: старые датасеты и все существующие
# вызовы обязаны воспроизводиться побайтово.
#
# В манифест ключи generation_version и generation_config
# пишутся ТОЛЬКО начиная с v2.1: манифесты v1 уже лежат
# на диске, и новые поля сделали бы их невоспроизводимыми.
# Отсутствие ключа значит v1.
# ============================================================

V1 = "v1"
V2_1 = "v2.1"

SUPERSEDED = {"v2": V2_1}

VERSIONS = (V1, V2_1)

DEFAULT_VERSION = V1

MANIFEST_KEY = "generation_version"
CONFIG_KEY = "generation_config"


# ============================================================
# РЕВИЗИЯ СХЕМЫ RAW
# ============================================================
#
# Версия это правила генерации, ревизия это набор колонок.
# Их две разные оси, и путать их нельзя: v2.1 первого выпуска
# уже лежит на диске со схемой ревизии 1, и её манифест не
# должен стать невоспроизводимым.
#
# 1  исходный контракт: session_id есть только у app_screens.
# 2  session_id есть и у app_operations, и у banners: событие,
#    рождённое внутри сессии, несёт её настоящий идентификатор.
#    Восстановления по времени нет: у события либо известна
#    принадлежность, либо оно остаётся отдельным.
#
# Манифест без ключа это ревизия 1, ровно как манифест без
# generation_version это v1.
# ============================================================

RAW_SCHEMA_REVISION = 2

REVISION_KEY = "raw_schema_revision"

REVISIONS = (1, 2)

REVISION_BY_VERSION: dict[str, int] = {V1: 1, V2_1: 2}


def check_version(version: str) -> str:

    if version in SUPERSEDED:
        raise ValueError(
            f"версия {version!r} заменена на {SUPERSEDED[version]!r}; "
            f"её датасет остаётся на диске, но заново не собирается"
        )

    if version not in VERSIONS:
        raise ValueError(f"неизвестная версия генерации: {version!r}")

    return version


def manifest_version(manifest: dict) -> str:
    """
    Версия готового датасета. Манифест без поля это v1.
    """

    return str(manifest.get(MANIFEST_KEY, V1))


def generation_config(version: str) -> dict | None:
    """
    Конфигурация правил, с которой собран датасет.

    Для v1 её нет: правила v1 это сам код и константы config.py,
    уже записанные в манифест.
    """

    if version == V1:
        return None

    from .v2.config import configuration

    return configuration()


def revision_for(version: str) -> int:
    """
    Ревизия схемы RAW, которую пишет эта версия генератора.

    V1 заморожена: её файлы и манифесты обязаны совпадать
    побайтово, поэтому она навсегда остаётся ревизией 1.
    """

    if version not in REVISION_BY_VERSION:
        raise ValueError(f"неизвестная версия генерации: {version!r}")

    return REVISION_BY_VERSION[version]


def manifest_revision(manifest: dict) -> int:
    """
    Ревизия схемы готового датасета. Манифест без поля это 1.
    """

    return int(manifest.get(REVISION_KEY, 1))
