# ============================================================


def month_factor(
    group: str,
    ts: datetime,
) -> float:
    """
    Базовый коэффициент месяца.
    """

    group_factors = MONTH_FACTORS.get(
        group
    )

    if group_factors is None:
        return 1.0

    return group_factors.get(
        ts.month,
        1.0,
    )


def weekend_factor(
    group: str,
    ts: datetime,
) -> float:
    """
    Saturday / Sunday.
    """

    if ts.weekday() < 5:
        return 1.0

    return WEEKEND_FACTORS.get(
        group,
        1.0,
    )


def holiday_factor(
    group: str,
    ts: datetime,
) -> float:
    """
    Общий special-date коэффициент.
    """

    return (
        march_holiday_factor(
            group,
            ts,
        )
        *
        back_to_school_factor(
            group,
            ts,
        )
        *
        new_year_factor(
            group,
            ts,
        )
    )


# ============================================================
# REGION FACTOR
# ============================================================


def region_factor(
    group: str,
    region: str | None,
    ts: datetime,
) -> float:
    """
    Региональный климатический эффект.

    Сейчас в первую очередь моделируем зиму.
    """

    if region is None:
        return 1.0

    if ts.month not in WINTER_MONTHS:
        return 1.0

    # Utilities отдельный случай.
    if group == "utilities":

        return (
            UTILITY_WINTER_REGION_FACTOR
            .get(
                region,
                1.0,
            )
        )

    return 1.0


# ============================================================
# CHANNEL FACTOR
# ============================================================


def channel_factor(
    group: str,
    channel: str,
    ts: datetime,
    region: str | None = None,
) -> float:
    """
    POS / online seasonal shift.

    Зимой:
        физический retail немного снижается,
        online / delivery растут.

    Сила зимнего эффекта зависит от региона.
    """

    key = (
        group,
        channel,
    )

    # --------------------------------------------------------
    # WINTER
    # --------------------------------------------------------

    if ts.month in WINTER_MONTHS:

        base = (
            WINTER_CHANNEL_FACTORS
            .get(
                key,
                1.0,
            )
        )

        if base == 1.0:
            return 1.0

        severity = 1.0

        if region is not None:

            severity = (
                WINTER_REGION_SEVERITY
                .get(
                    region,
                    1.0,
                )
            )

        # Если factor > 1:
        # усиливаем положительный эффект.
        #
        # Если factor < 1:
        # усиливаем падение.
        #
        # Пример:
        #
        # base = 1.35
        # severity = 1.20
        #
        # result =
        # 1 + (0.35 * 1.20)
        # = 1.42

        return (
            1.0
            +
            (
                base - 1.0
            )
            * severity
        )

    # --------------------------------------------------------
    # SUMMER
    # --------------------------------------------------------

    if ts.month in SUMMER_MONTHS:

        return (
            SUMMER_CHANNEL_FACTORS
            .get(
                key,
                1.0,
            )
        )

    return 1.0


# ============================================================
# FINAL CATEGORY SEASON FACTOR
# ============================================================


def season_factor(
    group: str,
    ts: datetime,
    region: str | None = None,
) -> float:
    """
    Общая сезонность категории БЕЗ учёта канала.

    month
        ×
    weekend
        ×
    holiday
        ×
    region
    """

    return (
        month_factor(
            group,
            ts,
        )
        *
        weekend_factor(
            group,
            ts,
        )
        *
        holiday_factor(
            group,
            ts,
        )
        *
        region_factor(
            group,
            region,
            ts,
        )
    )
