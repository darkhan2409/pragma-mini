# ============================================================
# HOLIDAY / SPECIAL WINDOWS
# ============================================================
#
# Здесь уже не просто месяц.
#
# Например:
#
# 8 марта
# Наурыз
# back-to-school
# Новый год
# post-holiday dip
# ============================================================


def march_holiday_factor(
    group: str,
    ts: datetime,
) -> float:
    """
    1–10 марта:
        8 марта / подарочный retail.

    18–25 марта:
        Наурыз.
    """

    if ts.month != 3:
        return 1.0

    # --------------------------------------------------------
    # 8 MARCH WINDOW
    # --------------------------------------------------------

    if 1 <= ts.day <= 10:

        factors = {
            "cosmetics": 1.35,
            "beauty": 1.25,
            "clothing": 1.15,
            "restaurant": 1.20,
            "coffee": 1.15,
            "marketplace": 1.15,
            "grocery": 1.05,
        }

        return factors.get(
            group,
            1.0,
        )

    # --------------------------------------------------------
    # NAURYZ
    # --------------------------------------------------------

    if 18 <= ts.day <= 25:

        factors = {
            "grocery": 1.20,
            "restaurant": 1.20,
            "fastfood": 1.10,
            "clothing": 1.15,
            "entertainment": 1.20,
            "travel": 1.10,
            "fuel": 1.05,
        }

        return factors.get(
            group,
            1.0,
        )

    return 1.0


def back_to_school_factor(
    group: str,
    ts: datetime,
) -> float:
    """
    Усиление расходов перед учебным годом.
    """

    # July preparation
    if ts.month == 7 and ts.day >= 15:

        factors = {
            "clothing": 1.10,
            "shoes": 1.10,
            "books": 1.10,
            "marketplace": 1.05,
        }

        return factors.get(
            group,
            1.0,
        )

