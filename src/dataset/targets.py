from datetime import datetime

from src.preprocessing.settings import GroupWindow


# ============================================================
# ИДЕЯ
# ============================================================
#
# Где вообще разрешено выбирать цели.
#
# Датасет НИЧЕГО не маскирует. Он только говорит, какие события
# лежат в периоде будущих целей своей группы: старая история
# validation и test остаётся видимым контекстом и оценочной
# целью не становится. Окончательный выбор целей это работа
# Masker.
#
# Период объявлен окном группы в настройках препроцессинга, и
# правило одно: [target_start, target_end). Вторая реализация
# «того же самого» рано или поздно разошлась бы с первой на
# границе.
#
# Изменение анкеты (profile_change) целью не бывает, хотя в ленте
# остаётся: анкета примера описывает клиента на cutoff событий, то
# есть уже после изменения, и закрытое новое значение она бы
# просто подсказала.
#
# Событие-источник вехи Lifelong целью тоже не бывает: веха в
# анкете несёт его время и суть, и закрытое событие она выдала
# бы. Какое событие — источник, говорит не время, а ссылка вехи
# на карту или договор (source_id), найденная препроцессингом:
# событие приходит уже с пометкой lifelong_source. Соседнее
# событие того же момента и все следующие карты, кредиты и вклады
# учатся как обычно.
# ============================================================


# Типы событий, которые остаются видимым контекстом, но целями
# MLM не становятся.
NOT_TARGET_TYPES: tuple[str, ...] = ("profile_change",)


def eligible(event_time: datetime, window: GroupWindow) -> bool:
    """
    Событие лежит в периоде будущих целей своей группы.

    Это признак периода и ничего больше: ни выбор масок, ни
    окончательная допустимость цели для конкретного Masker здесь
    не решаются.
    """

    return window.target_start <= event_time < window.target_end


def can_be_target(event_type: str | None) -> bool:
    """
    Может ли событие этого типа стать целью MLM.
    """

    return event_type not in NOT_TARGET_TYPES


__all__ = [
    "NOT_TARGET_TYPES",
    "can_be_target",
    "eligible",
]
