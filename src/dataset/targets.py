from __future__ import annotations

from datetime import datetime

from src.preprocessing.settings import GroupWindow


# ============================================================
# ИДЕЯ
# ============================================================
#
# Где вообще разрешено выбирать цели.
#
# Датасет НИЧЕГО не маскирует. Он только говорит, какие события
# лежат в периоде будущих целей своей группы: старая история
# validation и test остаётся видимым контекстом и оценочной
# целью не становится. Окончательный выбор целей это работа
# Masker.
#
# Период объявлен окном группы в настройках препроцессинга, и
# правило одно: [target_start, target_end). Вторая реализация
# «того же самого» рано или поздно разошлась бы с первой на
# границе.
# ============================================================


class TargetsError(ValueError):
    """
    Признак цели посчитать нельзя.
    """


def eligible(event_time: datetime, window: GroupWindow) -> bool:
    """
    Событие лежит в периоде будущих целей своей группы.

    Это признак периода и ничего больше: ни выбор масок, ни
    окончательная допустимость цели для конкретного Masker здесь
    не решаются.
    """

    return window.target_start <= event_time < window.target_end


__all__ = [
    "TargetsError",
    "eligible",
]
