# события ноль» при отсчёте от него. Его читает TimeRoPE, и его
# смена означает, что прежние позиции ему больше не подходят.
#
# IMPLEMENTATION_VERSION — версия кода пакета. Поднимается при
# ЛЮБОЙ правке модуля, даже если формат не тронут.
# ============================================================


