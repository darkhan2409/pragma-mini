from __future__ import annotations

from contextlib import contextmanager

import torch
from torch import nn


# ============================================================
# ЭНКОДЕР АНКЕТЫ
# ============================================================
#
# Анкета это два десятка полей ключ-значение, снятых на границу
# выгрузки. Внимание здесь двунаправленное и охватывает ВСЮ
# анкету одного клиента: полей мало, порядка между ними нет, и
# каждое вправе смотреть на каждое.
#
# Маркер [USR] уже лежит первым токеном анкеты — его записал тот
# же set_lead, что ставит [EVT] событию. Второго маркера не
# добавляется, и вектор клиента читается из колонки 0.
#
# Клиенты разделены строками батча: внимание не выходит за
# строку, поэтому анкета одного клиента не видит анкету другого
# по построению.
#
# ВРЕМЕННОГО КАНАЛА ЗДЕСЬ НЕТ, и это решение, а не пропуск. В
# эталоне у профиля включён TimeRoPE, но ненулевую позицию там
# получают только датированные жизненные вехи (открытие счёта,
# прохождение KYC) — отдельный поток «ключ + дата». Обычные поля
# снимка получают время ровно 0.0. У нас вех нет вовсе: анкета
# это один снимок, а её изменения лежат в ленте событий со своим
# event_time. Значит все позиции были бы нулями, а поворот на
# нулевой угол ничего не меняет. Канал, который не меняет ничего,
# не заводится.
#
# Событий, календаря и event_time этот слой не видит: ему их
# просто не подают.
#
# Заполнитель закрыт маской внимания. Занулять его выход, как
# делает энкодер события, здесь не нужно: наружу идёт только
# колонка 0, а она у каждого клиента настоящая — анкета без
# маркера отвергается ещё датасетом.
# ============================================================


class ProfileEncoder(nn.Module):
    """
    Блоки трансформера по анкете клиента, вектор из позиции [USR].
    """

    def __init__(
        self,
        dim: int,
        layers: int,
        heads: int,
        feedforward: int,
        dropout: float,
        seed: int,
    ):

        super().__init__()

        self.dim = int(dim)

        # Веса разыгрываются от известного состояния и не трогают
        # чужое: torch не даёт передать generator внутрь
        # TransformerEncoderLayer, поэтому глобальное состояние
        # сохраняется, подменяется и возвращается назад.
        #
        # Тот же приём есть в энкодере события. Повтор намеренный:
        # этапы держатся отдельно. Когда появится третий энкодер,
        # их стоит свести в один класс — в эталоне все три сделаны
        # одним Encoder.
        with _seeded(seed):

            # Слои собираются поштучно. nn.TransformerEncoder
            # копирует ОДИН слой, и тогда все блоки стартовали бы
            # с одинаковых весов.
            self.layers = nn.ModuleList(
                [
                    nn.TransformerEncoderLayer(
                        d_model=self.dim,
                        nhead=heads,
                        dim_feedforward=feedforward,
                        dropout=dropout,
                        activation="gelu",
                        batch_first=True,
                        norm_first=True,
                    )
                    for _ in range(layers)
                ]
            )

            self.norm = nn.LayerNorm(self.dim)

    def forward(self, tokens: torch.Tensor, pad: torch.Tensor) -> torch.Tensor:
        """
        [B, P, d] -> [B, d]: один вектор на клиента.
        """

        x = tokens

        for layer in self.layers:
            x = layer(x, src_key_padding_mask=pad)

        x = self.norm(x)

        # Маркер [USR] стоит первым токеном анкеты всегда, и
        # колонка 0 настоящая даже у анкеты из одного маркера.
        return x[:, 0]


@contextmanager
def _seeded(seed: int):
    """
    Известное состояние генератора на время сборки весов.
    """

    state = torch.get_rng_state()

    try:
        torch.manual_seed(int(seed))
        yield
    finally:
        torch.set_rng_state(state)


__all__ = ["ProfileEncoder"]
